#!/bin/sh
# selfhost up: writes the selfhost stack to /opt/selfhost/deploy/docker, then runs its
# install.sh, which installs Docker, starts the containers and schedules the daily backup.
# Runs once as root: as cloud-init user-data on a new server, or over SSH.
set -eu
mkdir -p /opt/selfhost/deploy/docker /opt/selfhost/deploy/docker/console
cd /opt/selfhost/deploy/docker
domain=selfhost.example.com
cat >compose.yml <<'SELFHOST_EOF'
services: {}
SELFHOST_EOF
cat >console/index.html <<'SELFHOST_EOF'
<p>console</p>
SELFHOST_EOF
cat >install.sh <<'SELFHOST_EOF'
#!/bin/sh
echo installed
SELFHOST_EOF
chmod 755 install.sh
umask 077
cat >.env.next <<'SELFHOST_EOF'
# Written by selfhost up. To change a setting, edit it here and run ./install.sh again.
# Keep a copy off the server: a restore needs the same tokens.
COMPOSE_FILE=compose.yml:compose.tls.yml
SELFHOST_IMAGE=ghcr.io/getselfhostai/selfhost
SELFHOST_VERSION=0.1.0
# Generated by install.sh on the server.
POSTGRES_PASSWORD=
SELFHOST_TOKEN=
SELFHOST_OTLP_TOKEN=
SELFHOST_SIGNIN_COOKIE_SECRET=
SELFHOST_SIGNIN_PROXY_SECRET=
# Only Caddy faces the internet; the API and the collector answer on this server alone.
SELFHOST_BIND=127.0.0.1
OTLP_BIND=127.0.0.1
SELFHOST_BACKUP_TIME=03:00
SELFHOST_BACKUP_KEEP_DAYS=14
SELFHOST_EOF
printf 'SELFHOST_DOMAIN=%s\nSELFHOST_PUBLIC_URL=https://%s\n' "$domain" "$domain" >>.env.next
exec sh ./install.sh </dev/null
