function readme(bundle: MdmBundle, files: Payload[]): string {
  return [
    `selfhost managed settings for ${MDM_NAMES[bundle.mdm]}`,
    "",
    `Compiled from ${bundle.config}${bundle.team ? ` for team ${bundle.team}` : ""}, config version ${bundle.policy_hash.slice(0, 12)}.`,
    "The scripts carry every file inside them and write only files whose sha256 differs. files/ holds",
    "plain copies to review, and manifest.json lists each file, its path and its sha256.",
    "",
    "Deploy:",
    ...STEPS[bundle.mdm],
    "",
    "Files:",
    ...files.map(
      (file) =>
        `- ${file.platform} ${file.scope === "user" ? `~/${file.target} in every home folder` : file.target}`,
    ),
    "",
    "Notes:",
    ...vendorNotes(files),
    "- The hooks run selfhost hook: install selfhost on every laptop (npm install -g selfhostai).",
    "- After selfhost join on a laptop, each sync reports its config version. selfhost team laptops,",
    "  or the Team screen of the console, lists the laptops that are behind or silent.",
    "- When selfhost.toml changes, run selfhost policy package again and replace the scripts.",
    "",
  ].join("\n");
}

function write(path: string, content: string, mode = 0o644): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content, { mode });
  chmodSync(path, mode);
}

/** Compiles selfhost.toml and writes the bundle for one device management tool. */
export function policyPackage(options: PackageOptions, io: PolicyPackageIo): MdmBundle {
  const mdm = parseMdm(options.mdm);
  const { location, config } = loadPolicy(io.cwd, options.config, io);
  checkTeam(config, options.team);
  const result = compilePolicy(config, {
    team: options.team,
    ...(options.hookCommand ? { hookCommand: options.hookCommand } : {}),
  });
  const root = repoDir(undefined, io.cwd);
  const out = resolve(io.cwd, options.out ?? join(root ?? io.cwd, ".selfhost", "mdm", mdm));
  rmSync(out, { recursive: true, force: true });
  const policyHash = sha256(readFileSync(location.path, "utf8"));
  const files = MDM_PLATFORMS[mdm].flatMap((platform) => payloads(result, platform));
  for (const file of files) write(join(out, file.file), file.content);

  const scripts: Record<string, string> = {};
  const darwin = files.filter((file) => file.platform === "darwin");
  const windows = files.filter((file) => file.platform === "win32");
  if (mdm === "jamf") {
    scripts["install.sh"] = installSh(mdm, policyHash, darwin);
    scripts["extension-attribute.sh"] = checkSh(mdm, policyHash, darwin, "result");
  } else if (mdm === "kandji") {
    scripts["audit.sh"] = checkSh(mdm, policyHash, darwin, "exit");
    scripts["remediation.sh"] = installSh(mdm, policyHash, darwin);
  } else {
    scripts["install.sh"] = installSh(mdm, policyHash, darwin);
    scripts["install.ps1"] = installPs1(mdm, policyHash, windows);
    scripts["detect.ps1"] = detectPs1(mdm, policyHash, windows);
  }
  for (const [name, content] of Object.entries(scripts)) {
    write(join(out, name), content, name.endsWith(".sh") ? 0o755 : 0o644);
  }

  const bundle: MdmBundle = {
    schema: "selfhost.mdm_bundle/v1",
    mdm,
    policy_hash: policyHash,
    config: location.path,
    team: options.team ?? null,
    out,
    files: files.map(({ content: _content, ...file }) => file),
    scripts: Object.keys(scripts),
    warnings:
      options.hookCommand === undefined && io.which && !io.which("selfhost")
        ? [NOT_ON_PATH_WARNING]
        : [],
  };
  const { out: _out, config: _config, warnings: _warnings, ...manifest } = bundle;
  write(join(out, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  write(join(out, "README.txt"), readme(bundle, files));

  if (options.json) {
    io.write(JSON.stringify(bundle, null, 2));
  } else {
    const shown = (path: string) => {
      const rel = relative(io.cwd, path);
      return rel === "" || rel.startsWith("..") ? path : rel;
    };
    for (const warning of bundle.warnings) io.write(`Note: ${warning}`);
    io.write(
      `Packaged ${plural(files.length, "managed settings file")} for ${MDM_NAMES[mdm]} into ${shown(out)}, config version ${policyHash.slice(0, 12)}.`,
    );
    for (const file of files) {
      io.write(
        `  ${file.platform}  ${file.scope === "user" ? `~/${file.target} (every user)` : file.target}`,
      );
    }
    io.write(
      `Give ${MDM_NAMES[mdm]} ${bundle.scripts.join(", ")}; README.txt says where each goes.`,
    );
  }
  return bundle;
}

/** Adds `policy package`, creating the `policy` group if it is not there. */
export function registerPolicyPackage(
  program: Command,
  io: () => PolicyPackageIo,
  fail: (error: unknown, json: boolean | undefined) => void,
): void {
  const policy =
    program.commands.find((c) => c.name() === "policy") ??
    program.command("policy").description("check and observe the rules in selfhost.toml");

  policy
    .command("package")
    .description(
      "bundle the compiled managed settings with install scripts for Jamf, Kandji or Intune",
    )
    .requiredOption("--mdm <tool>", "jamf, kandji or intune")
    .option("--out <dir>", "output folder (default: .selfhost/mdm/<tool> in the repository)")
    .option("--team <name>", "apply this team's overrides")
    .option("--hook-command <command>", "command the hooks run; {agent} is the agent id")
    .option("-c, --config <path>", "path to selfhost.toml")
    .option("--json", "print JSON")
    .action((options: PackageOptions) => {
      try {
        policyPackage(options, io());
      } catch (error) {
        fail(error, options.json);
      }
    });
}
