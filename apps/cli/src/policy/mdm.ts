/**
 * `selfhost policy package --mdm jamf|kandji|intune`: the managed settings files as a bundle a
 * device management tool runs on every laptop. Each bundle is self-contained scripts (the
 * files ride inside them, base64 encoded, with their sha256), the plain files for review, a
 * manifest and a short README. No vendor account is needed to build one.
 */

export const MDMS = ["jamf", "kandji", "intune"] as const;
export type Mdm = (typeof MDMS)[number];

const MDM_NAMES: Record<Mdm, string> = { jamf: "Jamf Pro", kandji: "Kandji", intune: "Intune" };

/** The platforms each tool's bundle covers. */
const MDM_PLATFORMS: Record<Mdm, Platform[]> = {
  jamf: ["darwin"],
  kandji: ["darwin"],
  intune: ["darwin", "win32"],
};

export interface MdmFile {
  vendor: CompileVendor;
  platform: Platform;
  /** system: one copy at a system path. user: a copy in every user's home folder. */
  scope: "system" | "user";
  /** The path the vendor reads; for user files relative to the home folder. */
  target: string;
  mode: "0644" | "0755";
  sha256: string;
  /** The plain copy in the bundle, relative to it. */
  file: string;
}

/** manifest.json in the bundle, and `selfhost policy package --json`. */
export interface MdmBundle {
  schema: "selfhost.mdm_bundle/v1";
  mdm: Mdm;
  /** sha256 of the selfhost.toml compiled: the config version laptops report. */
  policy_hash: string;
  config: string;
  team: string | null;
  out: string;
  files: MdmFile[];
  /** The scripts to give the tool, relative to the bundle. */
  scripts: string[];
  warnings: string[];
}

interface PackageOptions {
  mdm?: string;
  out?: string;
  config?: string;
  team?: string;
  hookCommand?: string;
  json?: boolean;
}

export interface PolicyPackageIo extends PolicyIo {
  which?: (name: string) => string | undefined;
}

const sha256 = (text: string) => createHash("sha256").update(text).digest("hex");
const base64 = (text: string) => Buffer.from(text, "utf8").toString("base64");

export function parseMdm(value: string | undefined): Mdm {
  const name = value?.trim().toLowerCase();
  const mdm = MDMS.find((candidate) => candidate === name);
  if (!mdm) throw new Error(`--mdm: expected jamf, kandji or intune, got "${value ?? ""}"`);
  return mdm;
}

interface Payload extends MdmFile {
  content: string;
}

/** The files of a compile for one platform: system files and the per-user ones. */
function payloads(result: CompileResult, platform: Platform): Payload[] {
  const system = managedFiles(result, platform).map(
    (file): Payload => ({
      vendor: file.vendor,
      platform,
      scope: "system",
      target: file.target,
      mode: file.mode,
      sha256: sha256(file.content),
      file: join("files", platform, file.vendor, file.name),
      content: file.content,
    }),
  );
  const user = result.vendors.flatMap((vendor) =>
    vendor.files.flatMap((file): Payload[] => {
      if (file.install.kind !== "mdm") return [];
      const target = file.install.paths[platform];
      if (target === undefined) return [];
      return [
        {
          vendor: vendor.vendor,
          platform,
          scope: "user",
          target: target.replace(/^~[\\/]/, ""),
          mode: "0644",
          sha256: sha256(file.content),
          file: join("files", platform, "home", vendor.vendor, file.name),
          content: file.content,
        },
      ];
    }),
  );
  return [...system, ...user];
}

const shQuote = (text: string) => `'${text.replaceAll("'", `'\\''`)}'`;
const psQuote = (text: string) => `'${text.replaceAll("'", "''")}'`;

function header(mdm: Mdm, policyHash: string, comment: string): string[] {
  return [
    `${comment} selfhost managed settings for ${MDM_NAMES[mdm]}, from selfhost.toml ${policyHash.slice(0, 12)}.`,
    `${comment} Generated by selfhost policy package. Compile and package again instead of editing.`,
  ];
}

/** The macOS script: writes each file that differs, as root, and checks every one it wrote. */
function installSh(mdm: Mdm, policyHash: string, files: Payload[]): string {
  const system = files.filter((file) => file.scope === "system");
  const user = files.filter((file) => file.scope === "user");
  const lines = [
    "#!/bin/sh",
    ...header(mdm, policyHash, "#"),
    "# Runs as root. Writes a file only when its sha256 differs, so it is safe to run on every check-in.",
    "",
    'if [ "$(/usr/bin/id -u)" -ne 0 ]; then',
    '  echo "Run as root: the device management agent runs scripts as root." >&2',
    "  exit 1",
    "fi",
    "status=0",
    "",
    "sum() { /usr/bin/shasum -a 256 \"$1\" | /usr/bin/awk '{print $1}'; }",
    "",
    "# put <path> <mode> <owner> <base64> <sha256>",
    "put() {",
    '  if [ -f "$1" ] && [ "$(sum "$1")" = "$5" ]; then echo "current $1"; return 0; fi',
    '  dir=$(/usr/bin/dirname "$1")',
    '  if [ ! -d "$dir" ]; then /bin/mkdir -p "$dir" && /usr/sbin/chown "$3" "$dir"; fi',
    '  tmp="$1.selfhost-$$"',
    '  printf \'%s\' "$4" | /usr/bin/base64 -D > "$tmp" || { /bin/rm -f "$tmp"; echo "failed $1" >&2; status=1; return 0; }',
    '  if [ "$(sum "$tmp")" != "$5" ]; then /bin/rm -f "$tmp"; echo "failed $1: checksum" >&2; status=1; return 0; fi',
    '  /usr/sbin/chown "$3" "$tmp" && /bin/chmod "$2" "$tmp" && /bin/mv -f "$tmp" "$1" || { /bin/rm -f "$tmp"; echo "failed $1" >&2; status=1; return 0; }',
    '  echo "installed $1"',
    "}",
    "",
    ...system.map(
      (file) =>
        `put ${shQuote(file.target)} ${file.mode} root:wheel ${shQuote(base64(file.content))} ${file.sha256}`,
    ),
  ];
  if (user.length > 0) {
    lines.push(
      "",
      "# Per-user files, in every home folder under /Users.",
      "for home in /Users/*; do",
      '  user=$(/usr/bin/basename "$home")',
      '  if [ "$user" = "Shared" ] || [ ! -d "$home" ]; then continue; fi',
      ...user.map(
        (file) =>
          `  put "$home"/${shQuote(file.target)} ${file.mode} "$user" ${shQuote(base64(file.content))} ${file.sha256}`,
      ),
      "done",
    );
  }
  lines.push("", 'exit "$status"', "");
  return lines.join("\n");
}

/**
 * A read-only macOS check of the system files. result: Jamf extension attribute output, with
 * the config version or how many files differ. exit: Kandji audit, 0 when every file matches.
 */
function checkSh(mdm: Mdm, policyHash: string, files: Payload[], style: "result" | "exit"): string {
  const system = files.filter((file) => file.scope === "system");
  const lines = [
    "#!/bin/sh",
    ...header(mdm, policyHash, "#"),
    style === "result"
      ? "# Extension attribute: prints current <version>, or pending <n> when files differ."
      : "# Audit: exits 0 when every managed file matches, 1 so the remediation script runs.",
    "",
    "pending=0",
    "check() {",
    '  if [ ! -f "$1" ] || [ "$(/usr/bin/shasum -a 256 "$1" | /usr/bin/awk \'{print $1}\')" != "$2" ]; then',
    '    echo "differs $1" >&2',
    "    pending=$((pending + 1))",
    "  fi",
    "}",
    ...system.map((file) => `check ${shQuote(file.target)} ${file.sha256}`),
    "",
  ];
  if (style === "result") {
    lines.push(
      'if [ "$pending" -eq 0 ]; then',
      `  echo "<result>current ${policyHash.slice(0, 12)}</result>"`,
      "else",
      '  echo "<result>pending $pending</result>"',
      "fi",
      "exit 0",
      "",
    );
  } else {
    lines.push('if [ "$pending" -eq 0 ]; then exit 0; fi', "exit 1", "");
  }
  return lines.join("\n");
}

const PS_PUT = [
  "$status = 0",
  "",
  "function Get-Sum([string]$Path) { (Get-FileHash -Algorithm SHA256 -LiteralPath $Path).Hash.ToLowerInvariant() }",
  "",
  "function Put([string]$Path, [string]$Data, [string]$Want) {",
  '  if ((Test-Path -LiteralPath $Path) -and ((Get-Sum $Path) -eq $Want)) { Write-Output "current $Path"; return }',
  "  try {",
  "    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $Path) | Out-Null",
  '    $tmp = "$Path.selfhost-$PID"',
  "    [IO.File]::WriteAllBytes($tmp, [Convert]::FromBase64String($Data))",
  "    if ((Get-Sum $tmp) -ne $Want) {",
  "      Remove-Item -Force -LiteralPath $tmp",
  '      Write-Output "failed $Path: checksum"; $script:status = 1; return',
  "    }",
  "    Move-Item -Force -LiteralPath $tmp -Destination $Path",
  '    Write-Output "installed $Path"',
  "  } catch {",
  '    Write-Output "failed $Path: $_"; $script:status = 1',
  "  }",
  "}",
];

/** The Windows script: run as SYSTEM in 64-bit PowerShell. */
function installPs1(mdm: Mdm, policyHash: string, files: Payload[]): string {
  const system = files.filter((file) => file.scope === "system");
  const user = files.filter((file) => file.scope === "user");
  const lines = [
    ...header(mdm, policyHash, "#"),
    "# Runs as SYSTEM in 64-bit PowerShell. Writes a file only when its sha256 differs.",
    "",
    ...PS_PUT,
    "",
    ...system.map(
      (file) => `Put ${psQuote(file.target)} ${psQuote(base64(file.content))} '${file.sha256}'`,
    ),
  ];
  if (user.length > 0) {
    lines.push(
      "",
      "# Per-user files, in every profile folder.",
      `$skip = @('Public', 'Default', 'Default User', 'All Users')`,
      'Get-ChildItem -Directory -LiteralPath "$env:SystemDrive\\Users" | Where-Object { $skip -notcontains $_.Name } | ForEach-Object {',
      ...user.map(
        (file) =>
          `  Put (Join-Path $_.FullName ${psQuote(file.target.replaceAll("/", "\\"))}) ${psQuote(base64(file.content))} '${file.sha256}'`,
      ),
      "}",
    );
  }
  lines.push("", "exit $status", "");
  return lines.join("\r\n");
}

/** Intune Remediations detection: exit 0 when every system file matches, 1 to remediate. */
function detectPs1(mdm: Mdm, policyHash: string, files: Payload[]): string {
  const system = files.filter((file) => file.scope === "system");
  return [
    ...header(mdm, policyHash, "#"),
    "# Detection: exits 0 when every managed file matches, 1 so Intune runs install.ps1.",
    "",
    "$pending = 0",
    "foreach ($file in @(",
    system.map((file) => `  @(${psQuote(file.target)}, '${file.sha256}')`).join(",\r\n"),
    ")) {",
    "  $path = $file[0]",
    "  if (-not (Test-Path -LiteralPath $path) -or (Get-FileHash -Algorithm SHA256 -LiteralPath $path).Hash.ToLowerInvariant() -ne $file[1]) {",
    '    Write-Output "differs $path"; $pending++',
    "  }",
    "}",
    "if ($pending -eq 0) { exit 0 }",
    "exit 1",
    "",
  ].join("\r\n");
}

function vendorNotes(files: Payload[]): string[] {
  const vendors = new Set(files.map((file) => file.vendor));
  const notes: string[] = [];
  if (vendors.has("claude_code")) {
    notes.push(
      "- Claude Code reads the managed-settings.d/selfhost.json drop-in next to any managed-settings.json. If you already deploy a Claude Code configuration profile (com.anthropic.claudecode) or the HKLM Settings value, Claude Code uses that source alone unless it sets managedSourcesBehavior to merge (Claude Code 2.1.242 or later). Check with /status in Claude Code: Setting sources should list Enterprise managed settings (drop-ins).",
    );
  }
  if (vendors.has("codex")) {
    notes.push(
      "- Codex reads one requirements.toml. This bundle replaces it: if you already deliver one, merge by hand first. A com.openai.codex requirements_toml_base64 profile ranks above the file.",
    );
  }
  if (vendors.has("copilot")) {
    notes.push(
      "- Copilot reads one managed-settings.json, replaced by this bundle. The .github-private repository route (selfhost policy compile --apply) needs no device management.",
    );
  }
  if (vendors.has("cursor")) {
    notes.push(
      "- Cursor reads the enterprise hooks.json. Team rules still go in the Cursor dashboard.",
    );
  }
  return notes;
}

