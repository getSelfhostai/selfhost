// Writes src/vendor/ccusage/pricing-snapshot.ts from the two price tables ccusage v20.0.48
// embeds in its binary, so cost estimates work offline and match ccusage.
//
//   node scripts/gen-pricing-snapshot.mjs <litellm.json> <models-dev-pricing.json>
//
// <litellm.json> is LiteLLM's model_prices_and_context_window.json at the commit ccusage pins in
// flake.lock (nodes.litellm). <models-dev-pricing.json> is
// rust/crates/ccusage-pricing-snapshots/src/models-dev-pricing.json from the ccusage repo.
// The compaction mirrors ccusage's ccusage-pricing-snapshots/build.rs, limited to the model
// families Claude Code and Codex report. Run `pnpm biome format --write` on the output.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const CCUSAGE_VERSION = "20.0.48";
const LITELLM_COMMIT = "1046716b6d3d45f30d5efad42becbd440d6187ee";

const [litellmPath, modelsDevPath] = process.argv.slice(2);
if (!litellmPath || !modelsDevPath) {
  console.error("usage: gen-pricing-snapshot.mjs <litellm.json> <models-dev-pricing.json>");
  process.exit(1);
}

// ccusage-pricing-snapshots/build.rs is_embedded_model, limited to bare ids and Bedrock-style
// Anthropic ids: Claude Code and Codex log model ids without a provider prefix.
function isEmbeddedLiteLlmModel(model) {
  return isBareModel(model) || /^(anthropic\.|(us|eu|global|jp|au)\.anthropic\.)/.test(model);
}

function isBareModel(model) {
  return (
    model.startsWith("claude-") ||
    model.startsWith("gpt-") ||
    model === "o3" ||
    model.startsWith("o3-") ||
    model === "o4-mini" ||
    model.startsWith("o4-mini-")
  );
}

const LITELLM_FIELDS = [
  ["input_cost_per_token", "i"],
  ["output_cost_per_token", "o"],
  ["cache_creation_input_token_cost", "cc"],
  ["cache_read_input_token_cost", "cr"],
  ["input_cost_per_token_above_200k_tokens", "ia"],
  ["output_cost_per_token_above_200k_tokens", "oa"],
  ["cache_creation_input_token_cost_above_200k_tokens", "cca"],
  ["cache_read_input_token_cost_above_200k_tokens", "cra"],
];

function compactLiteLlm(raw) {
  const out = {};
  for (const model of Object.keys(raw).sort()) {
    const pricing = raw[model];
    if (!isEmbeddedLiteLlmModel(model) || pricing === null || typeof pricing !== "object") continue;
    const fields = {};
    for (const [source, target] of LITELLM_FIELDS) {
      const value = pricing[source];
      if (typeof value === "number") fields[target] = value;
    }
    for (const tier of ["fast", "flex"]) {
      const value = pricing.provider_specific_entry?.[tier];
      if (typeof value === "number") fields[tier] = value;
    }
    if (fields.i !== undefined && fields.o !== undefined) out[model] = fields;
  }
  return out;
}

function compactModelsDev(raw) {
  const out = {};
  for (const model of Object.keys(raw).sort()) {
    const entry = raw[model];
    const cost = entry?.cost;
    if (!isBareModel(model) || typeof cost?.input !== "number" || typeof cost.output !== "number") {
      continue;
    }
    if (cost.input === 0 && cost.output === 0) continue;
    const fields = { i: cost.input, o: cost.output };
    if (typeof cost.cache_read === "number") fields.cr = cost.cache_read;
    if (typeof cost.cache_write === "number") fields.cw = cost.cache_write;
    if (entry.exactOnly === true) fields.x = true;
    const tier = (cost.tiers ?? [])
      .filter((band) => band?.tier?.type === "context" && band.tier.size > 0)
      .sort((a, b) => a.tier.size - b.tier.size)[0];
    if (tier) {
      const band = { size: tier.tier.size };
      for (const [source, target] of [
        ["input", "i"],
        ["output", "o"],
        ["cache_read", "cr"],
        ["cache_write", "cw"],
      ]) {
        if (typeof tier[source] === "number") band[target] = tier[source];
      }
      fields.t = band;
    }
    out[model] = fields;
  }
  return out;
}

const litellm = compactLiteLlm(JSON.parse(readFileSync(litellmPath, "utf8")));
const modelsDev = compactModelsDev(JSON.parse(readFileSync(modelsDevPath, "utf8")));

const header = `// Generated by scripts/gen-pricing-snapshot.mjs. Do not edit by hand.
//
// Offline price tables, as embedded by ccusage v${CCUSAGE_VERSION} (MIT, see ./LICENSE):
// - LITELLM: BerriAI/litellm model_prices_and_context_window.json at ${LITELLM_COMMIT}
//   (MIT), compacted like ccusage-pricing-snapshots/build.rs. USD per token.
// - MODELS_DEV: ccusage-pricing-snapshots/src/models-dev-pricing.json (from models.dev, MIT),
//   bare Claude and OpenAI model ids only. USD per million tokens; x marks exact-only ids and t
//   is the lowest long-context tier.
import type { LiteLlmRates, ModelsDevRates } from "./pricing.js";

export const CCUSAGE_VERSION = "${CCUSAGE_VERSION}";
export const LITELLM_COMMIT = "${LITELLM_COMMIT}";
`;

const body = `
export const LITELLM: Record<string, LiteLlmRates> = ${JSON.stringify(litellm, null, 2)};

export const MODELS_DEV: Record<string, ModelsDevRates> = ${JSON.stringify(modelsDev, null, 2)};
`;

const out = join(
  dirname(fileURLToPath(import.meta.url)),
  "../src/vendor/ccusage/pricing-snapshot.ts",
);
writeFileSync(out, header + body);
console.log(
  `wrote ${out}: ${Object.keys(litellm).length} LiteLLM and ${Object.keys(modelsDev).length} models.dev entries`,
);
