import { defineConfig } from "tsup";

// The GitHub Action runs action/index.mjs straight from a checkout of this repository, with no
// install, so everything but Node itself is bundled into that one file. Playwright is not: the
// action installs playwright-core next to it and the receipt loads it when it takes screenshots.
export default defineConfig({
  entry: { index: "src/action/entry.ts" },
  outDir: "action",
  format: "esm",
  outExtension: () => ({ js: ".mjs" }),
  platform: "node",
  target: "node20",
  clean: false,
  splitting: false,
  sourcemap: false,
  minify: true,
  noExternal: [/.*/],
  external: ["playwright-core"],
  banner: {
    js: '// Generated by `pnpm --filter @selfhost/ee-receipt bundle` from ee/receipt/src. Do not edit.\nimport { createRequire as __receiptRequire } from "node:module"; const require = __receiptRequire(import.meta.url);',
  },
});
